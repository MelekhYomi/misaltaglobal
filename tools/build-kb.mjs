// Builds api/_kb.mjs: the knowledge Misalta AI answers from, taken from the site itself
// (company data in script.js plus the visible text of every public page).
// Run after any content change:  node tools/build-kb.mjs
// tools/check.mjs fails if api/_kb.mjs is out of date.
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "api", "_kb.mjs");

// Pages the assistant learns from, in reading order. Legal and utility pages are summarised elsewhere.
const PAGES = ["index", "about", "businesses", "consulting", "farms", "agro-processing", "agro-hubs", "logistics",
  "training", "trade-x", "trade-x/what_to_expect", "energy", "construction", "investment", "trust", "faq", "contact", "blog"];

const text = html => html
  .replace(/<head[\s\S]*?<\/head>|<script[\s\S]*?<\/script>|<style[\s\S]*?<\/style>|<svg[\s\S]*?<\/svg>|<form[\s\S]*?<\/form>/g, " ")
  .replace(/<(h[1-4])[^>]*>/g, "\n## ").replace(/<\/(p|li|h[1-4]|div|section|details|summary|tr)>/g, "\n")
  .replace(/<[^>]+>/g, " ")
  .replace(/&amp;/g, "&").replace(/&nbsp;/g, " ").replace(/&#39;|&rsquo;/g, "'").replace(/&quot;/g, '"').replace(/&lt;/g, "<").replace(/&gt;/g, ">")
  .replace(/[ \t]+/g, " ").replace(/ *\n */g, "\n").replace(/\n{2,}/g, "\n").trim();

// Git on Windows may check files out with CRLF line endings; build from LF so the output is the same everywhere.
export const lf = s => s.replace(/\r\n/g, "\n");

function siteData() {
  const js = lf(readFileSync(join(ROOT, "script.js"), "utf8"));
  // The data blocks at the top of script.js are plain literals; run just those in a sandbox.
  const head = js.slice(0, js.indexOf("const E = CONFIG.emails;"));
  const cred = js.slice(js.indexOf("const CRED_REVIEWED"), js.indexOf("const credRow"));
  const ctx = {};
  vm.runInNewContext(`${head}\n${cred}\nthis.out = { CONFIG, BUSINESSES, STATUS, NEWS, TEAM: typeof TEAM !== "undefined" ? TEAM : null, CREDENTIALS, CRED_STATUS, PARTNER_TYPES };`, ctx);
  return ctx.out;
}

export function buildKB() {
  const d = siteData();
  const c = d.CONFIG;
  const lines = [];
  lines.push("# Company facts (authoritative)");
  lines.push(`Legal name: ${c.company} (${c.rc}). Short name: ${c.short}.`);
  lines.push(`Phone and WhatsApp: ${c.phone} (WhatsApp link https://wa.me/${c.whatsapp}). Head office address: ${c.address}.`);
  lines.push("Team emails: " + Object.entries(c.emails).map(([k, v]) => `${k}: ${v}`).join("; ") + ".");
  lines.push("Social: " + Object.entries(c.social).map(([k, v]) => v ? `${k} ${v}` : `${k} (address not published yet; do not give one)`).join("; ") + ".");
  lines.push("Reply time: the team replies within two business days.");
  lines.push("\n# Leadership (a role with no name is still to be announced; never invent names)");
  for (const v of Object.values(c.team || {}))
    for (const p of [].concat(v)) if (p && p.title) lines.push(`- ${p.title}: ${p.name || "to be announced"}. ${p.bio || ""}`);
  lines.push("\n# Businesses (status: " + Object.entries(d.STATUS).map(([k, v]) => `${k} = ${v}`).join(", ") + ")");
  for (const b of d.BUSINESSES) lines.push(`- ${b.name} [${d.STATUS[b.status]}] (${b.group === "chain" ? "value chain stage " + b.stage : "enabler: " + b.stage}) page: /${b.page.replace(".html", "")}. ${b.line} For: ${b.who}.`);
  lines.push("\n# Licences, registrations and certifications register (status: " + Object.entries(d.CRED_STATUS).map(([k, v]) => `${k} = ${v[0]}`).join(", ") + ")");
  for (const e of d.CREDENTIALS) {
    lines.push(`## ${e.name || e.id}`);
    for (const [t, issuer, why, st, ref] of e.items) lines.push(`- ${t} | ${issuer} | ${d.CRED_STATUS[st][0]}${ref && ref !== "xxxxxx" ? " | ref " + ref : ""}. ${why}`);
  }
  lines.push("\n# Partner types we are building with");
  for (const [, t, desc] of d.PARTNER_TYPES) lines.push(`- ${t}: ${desc}`);
  lines.push("\n# News");
  for (const n of d.NEWS) lines.push(`- ${n.date}: ${n.title}. ${n.lede} (/news#${n.slug})`);
  lines.push("\n# Website pages (visible text)");
  for (const p of PAGES) {
    const html = lf(readFileSync(join(ROOT, p + ".html"), "utf8"));
    lines.push(`\n=== Page /${p === "index" ? "" : p} ===\n${text(html)}`);
  }
  return lines.join("\n");
}

const kb = buildKB();
const file = `// Generated by tools/build-kb.mjs from the website content. Do not edit by hand.\nexport const KB = ${JSON.stringify(kb)};\n`;
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(OUT, file);
  console.log(`api/_kb.mjs: ${kb.length.toLocaleString()} characters (~${Math.round(kb.length / 4).toLocaleString()} tokens)`);
}
export const KB_FILE = file;
